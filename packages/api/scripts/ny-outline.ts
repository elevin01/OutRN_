/**
 * Regenerates src/service/ny-outline.ts: New York State's outline around the service areas, from
 * the US Census Bureau's TIGERweb (public domain), clipped to REGION and simplified to about 5 m.
 *
 *   pnpm --filter @outrn/api ny-outline
 *
 * An aerial photo comes from New York State's orthoimagery, which covers the state and little past
 * it: a venue in Greenwich or across the Hudson gets none. Rerun when an area reaches past REGION.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

type Pt = [number, number]; // [lon, lat]

/** West, south, east, north: every service area's reach, with room to spare. */
const REGION = { w: -74.3, s: 40.45, e: -73.4, n: 41.45 };
const TOLERANCE_M = 5;

const url =
  "https://tigerweb.geo.census.gov/arcgis/rest/services/TIGERweb/State_County/MapServer/0/query?" +
  new URLSearchParams({
    where: "STUSAB='NY'",
    geometry: `${REGION.w},${REGION.s},${REGION.e},${REGION.n}`,
    geometryType: "esriGeometryEnvelope",
    inSR: "4326",
    spatialRel: "esriSpatialRelIntersects",
    outFields: "STUSAB",
    returnGeometry: "true",
    outSR: "4326",
    f: "json",
  }).toString();

/** Sutherland–Hodgman: a ring clipped to the (convex) region. */
function clip(ring: Pt[]): Pt[] {
  const edges: [(p: Pt) => boolean, (a: Pt, b: Pt) => Pt][] = [
    [(p) => p[0] >= REGION.w, (a, b) => at(a, b, (b[0] - REGION.w) / (b[0] - a[0]))],
    [(p) => p[0] <= REGION.e, (a, b) => at(a, b, (b[0] - REGION.e) / (b[0] - a[0]))],
    [(p) => p[1] >= REGION.s, (a, b) => at(a, b, (b[1] - REGION.s) / (b[1] - a[1]))],
    [(p) => p[1] <= REGION.n, (a, b) => at(a, b, (b[1] - REGION.n) / (b[1] - a[1]))],
  ];
  let out = ring;
  for (const [inside, cross] of edges) {
    const input = out;
    out = [];
    for (let i = 0; i < input.length; i++) {
      const cur = input[i]!;
      const prev = input[(i + input.length - 1) % input.length]!;
      if (inside(cur)) {
        if (!inside(prev)) out.push(cross(prev, cur));
        out.push(cur);
      } else if (inside(prev)) out.push(cross(prev, cur));
    }
  }
  return out;
}
/** The point a fraction t back from b toward a. */
const at = (a: Pt, b: Pt, t: number): Pt => [b[0] + (a[0] - b[0]) * t, b[1] + (a[1] - b[1]) * t];

/** Douglas–Peucker in metres (an equirectangular projection is plenty at this size). */
function simplify(ring: Pt[]): Pt[] {
  if (ring.length < 4) return ring;
  const k = Math.cos((41 * Math.PI) / 180);
  const m = (p: Pt): Pt => [p[0] * 111_320 * k, p[1] * 110_574];
  const keep = new Uint8Array(ring.length);
  keep[0] = keep[ring.length - 1] = 1;
  const stack: [number, number][] = [[0, ring.length - 1]];
  while (stack.length) {
    const [i, j] = stack.pop()!;
    const [ax, ay] = m(ring[i]!);
    const [bx, by] = m(ring[j]!);
    let best = -1;
    let far = 0;
    for (let x = i + 1; x < j; x++) {
      const [px, py] = m(ring[x]!);
      const dx = bx - ax;
      const dy = by - ay;
      const len = Math.hypot(dx, dy);
      const d = len ? Math.abs(dy * px - dx * py + bx * ay - by * ax) / len : Math.hypot(px - ax, py - ay);
      if (d > far) [far, best] = [d, x];
    }
    if (best > 0 && far > TOLERANCE_M) {
      keep[best] = 1;
      stack.push([i, best], [best, j]);
    }
  }
  return ring.filter((_, x) => keep[x]);
}

const res = await fetch(url);
if (!res.ok) throw new Error(`TIGERweb answered ${res.status}`);
const body = (await res.json()) as { features?: { geometry: { rings: Pt[][] } }[] };
const rings = (body.features ?? []).flatMap((f) => f.geometry.rings).map(clip).filter((r) => r.length >= 3).map(simplify).filter((r) => r.length >= 3);
if (!rings.length) throw new Error("TIGERweb returned no outline for New York");
const r6 = (n: number) => Math.round(n * 1e6) / 1e6;
const out = `// Generated by scripts/ny-outline.ts from the US Census Bureau's TIGERweb (public domain): New York
// State's outline within ${JSON.stringify(REGION)}, simplified to about ${TOLERANCE_M} m. Do not edit; rerun the script.
// Rings of [lon, lat]; a point is in New York when an odd number of rings hold it.
export const NY_REGION = ${JSON.stringify(REGION)} as const;
export const NY_RINGS: readonly (readonly (readonly [number, number])[])[] = ${JSON.stringify(rings.map((r) => r.map(([x, y]) => [r6(x), r6(y)])))};
`;
const file = join(dirname(fileURLToPath(import.meta.url)), "../src/service/ny-outline.ts");
writeFileSync(file, out);
console.log(`wrote ${rings.length} rings, ${rings.reduce((n, r) => n + r.length, 0)} points to ${file}`);
